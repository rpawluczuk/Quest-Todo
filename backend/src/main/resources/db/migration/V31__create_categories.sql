CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(60) NOT NULL,
    name_key VARCHAR(60) NOT NULL,
    icon VARCHAR(32) NOT NULL,
    color VARCHAR(32) NOT NULL,
    CONSTRAINT categories_name_not_blank CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT categories_name_key_not_blank CHECK (CHAR_LENGTH(TRIM(name_key)) > 0),
    CONSTRAINT categories_icon_valid CHECK (icon IN (
        'HEART', 'BRIEFCASE', 'HOME', 'BOOK', 'DUMBBELL',
        'WALLET', 'PEOPLE', 'STAR', 'LEAF', 'OTHER'
    )),
    CONSTRAINT categories_color_valid CHECK (color IN (
        'RED', 'ORANGE', 'AMBER', 'GREEN', 'TEAL', 'BLUE', 'PURPLE', 'PINK'
    )),
    CONSTRAINT categories_user_name_unique UNIQUE (user_id, name_key)
);

CREATE INDEX categories_user_id_idx ON categories(user_id);
