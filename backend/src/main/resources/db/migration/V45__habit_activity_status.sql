ALTER TABLE habits ADD COLUMN activity_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE habits ADD CONSTRAINT ck_habit_activity_status
    CHECK (activity_status IN ('ACTIVE', 'PLANNED', 'PAUSED'));

CREATE TABLE habit_status_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL REFERENCES habits(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'PLANNED', 'PAUSED')),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    open_slot INTEGER,
    CONSTRAINT ck_habit_status_period_bounds CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT ck_habit_status_period_open CHECK (
        (ended_at IS NULL AND open_slot IS NOT NULL AND open_slot = 1)
        OR (ended_at IS NOT NULL AND open_slot IS NULL)),
    CONSTRAINT uq_habit_status_open UNIQUE (habit_id, open_slot)
);
CREATE INDEX idx_habit_status_history ON habit_status_periods(habit_id, started_at, id);

-- created_on is only a calendar date, not a reliable creation instant.
-- Earlier history remains unknown; it must not be interpreted as a pause.
INSERT INTO habit_status_periods(habit_id, status, started_at, open_slot)
SELECT id, 'ACTIVE', CURRENT_TIMESTAMP, 1 FROM habits;
